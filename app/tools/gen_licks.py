"""The examples PLAY loops: licks.tab to a C header (fm1.toml gen), refusing what a real harmonica cannot do.

  gen_licks.py licks.tab --out build/gen/licks.h [--test tests/licks.txt]

--test also writes the script that plays and records every lick in turn, each held through one pass."""
import argparse
import re
import sys
from pathlib import Path

GAP_MS = 30                               # app.c: the breath demo_run leaves after each step
TUN = {                                   # as app.c TUN[]: T_ name, blow, draw; a harmonica whose hole 1 blows C4
    "major": ("T_MAJOR", [0, 4, 7, 12, 16, 19, 24, 28, 31, 36], [2, 7, 11, 14, 17, 21, 23, 26, 29, 33]),
    "melody": ("T_MELODY", [0, 4, 9, 12, 16, 19, 24, 28, 31, 36], [2, 7, 11, 14, 18, 21, 23, 26, 30, 33]),
    "natural": ("T_NATMIN", [0, 3, 7, 12, 15, 19, 24, 27, 31, 36], [2, 7, 10, 14, 17, 21, 22, 26, 29, 33]),
    "harmonic": ("T_HARMIN", [0, 3, 7, 12, 15, 19, 24, 27, 31, 36], [2, 7, 11, 14, 17, 20, 23, 26, 29, 32]),
}
TOKEN = re.compile(r"^(r|[+-]\d+'*(?:,[+-]\d+)*)(?::(\d*\.?\d+))?$")


def fail(lick, msg):
    sys.exit(f"licks.tab: {lick}: {msg}")


def parse(path):
    licks, cur = [], None
    for raw in Path(path).read_text().splitlines():
        line = raw.split("#")[0].strip()
        if not line:
            continue
        if line.startswith("lick "):
            _, name, tuning, beat, what = line.split(None, 4)
            cur = dict(name=name, tuning=tuning, beat=float(beat), what=what, phrases={}, tokens=[])
            licks.append(cur)
        elif line.startswith("= "):
            parts = line.split()
            cur["phrases"][parts[1]] = parts[2:]
        else:
            for t in line.split():
                m = re.fullmatch(r"@(\w+)(?:\*(\d+))?", t)
                if m:
                    if m[1] not in cur["phrases"]:
                        fail(cur["name"], f"no phrase {m[1]}")
                    cur["tokens"] += cur["phrases"][m[1]] * int(m[2] or 1)
                else:
                    cur["tokens"].append(t)
    return licks


def steps_of(lick):
    """[(holes as id + 1, bend, ms)], every step checked against the harmonica"""
    if lick["tuning"] not in TUN:
        fail(lick["name"], f"no tuning {lick['tuning']}")
    _, blow, draw = TUN[lick["tuning"]]
    steps = []
    for tok in lick["tokens"]:
        m = TOKEN.match(tok)
        if not m:
            fail(lick["name"], f"bad token {tok}")
        ms = int(round(float(m[2] or 1) * lick["beat"])) - GAP_MS
        if ms < 40:
            fail(lick["name"], f"{tok}: too short")
        if m[1] == "r":
            steps.append(([], 0, ms))
            continue
        holes = m[1].split(",")
        bend = holes[0].count("'")
        holes = [h.replace("'", "") for h in holes]
        nums = [int(h[1:]) for h in holes]
        if len({h[0] for h in holes}) > 1:
            fail(lick["name"], f"{tok}: one breath, blown or drawn")
        if max(nums) - min(nums) > 3 or len(set(nums)) != len(nums):
            fail(lick["name"], f"{tok}: a mouth covers up to 4 neighbouring holes")
        if any(not 1 <= n <= 10 for n in nums):
            fail(lick["name"], f"{tok}: holes 1 to 10")
        d = holes[0][0] == "-"
        ids = [(10 if d else 0) + n - 1 for n in nums]
        first = nums[0] - 1
        room = max(0, (draw[first] - blow[first] if d else blow[first] - draw[first]) - 1)
        if bend > room:
            fail(lick["name"], f"{tok}: this hole bends {room} half step(s) on a {lick['tuning']} harmonica")
        steps.append(([i + 1 for i in ids], bend, ms))
    if not 0 < len(steps) < 256:
        fail(lick["name"], f"{len(steps)} steps: 1 to 255")
    return steps


def write_header(licks, out):
    names = [l["name"] for l in licks]
    if len(set(names)) != len(names) or any(len(n) > 7 for n in names):
        sys.exit("licks.tab: names must be unique, 7 letters at most")
    lines = ["/* generated by tools/gen_licks.py from licks.tab */"]
    table = []
    for l in licks:
        steps = steps_of(l)
        lines.append(f"static const lstep_t L_{l['name']}[] = {{   /* {l['what']} */")
        row = "   "
        for holes, bend, ms in steps:
            s = " {{%s}, %d, %d}," % (", ".join(map(str, holes)) or "0", bend, ms)
            if len(row) + len(s) > 118:
                lines.append(row)
                row = "   "
            row += s
        lines += [row, "};"]
        pos = re.search(r"\b([1-4])(?:st|nd|rd|th) position", l["what"])   # the description names the position
        table.append('    {"%s", L_%s, %d, %s, %s},' % (l["name"], l["name"], len(steps), TUN[l["tuning"]][0],
                                                      pos[1] if pos else 0))
    lines += ["static const struct {", "    const char *name;", "    const lstep_t *steps;", "    uint8_t n;",
              "    uint8_t tuning;                      /* the harmonica it is written for (T_*) */",
              "    uint8_t pos;                         /* the position it is played in, 1..4 (0: not said) */",
              "} LICKS[] = {", *table, "};"]
    Path(out).write_text("\n".join(lines) + "\n")
    secs = [sum(s[2] + GAP_MS for s in steps_of(l)) / 1000 for l in licks]
    print(f"licks: {len(licks)}, {min(secs):.0f} to {max(secs):.0f} s each")


def write_test(licks, out):
    """every lick for one pass, each group on its own harmonica (ALGORITHM moves on to the next tuning first)"""
    lines = ["# generated by tools/gen_licks.py: every lick, recorded one after the other, to listen to:",
             "#   app/build/host/harmonica_host app/tests/licks.txt app/build/host",
             "# PLAY loops a lick; SELECT while it plays moves to the next, which starts at once; PLAY again stops",
             "wait 600", "wav licks.wav", "tap PLAY"]
    for i, l in enumerate(licks):
        lines += [f"# {l['name']}", f"wait {sum(s[2] + GAP_MS for s in steps_of(l)) + 150}"]
        if i + 1 < len(licks):
            if licks[i + 1]["tuning"] != l["tuning"]:
                lines.append("turn ALGO 1")
            lines.append("turn SELECT 1")
    lines += ["tap PLAY", "wait 300", "wavstop", "expect holes 0", f"expect lick {len(licks) - 1}", "expect tuning 3"]
    Path(out).write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tab")
    ap.add_argument("--out", required=True)
    ap.add_argument("--test")
    a = ap.parse_args()
    licks = parse(a.tab)
    write_header(licks, a.out)
    if a.test:
        write_test(licks, a.test)


if __name__ == "__main__":
    main()
